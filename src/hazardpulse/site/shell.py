def jsonld_for(path: str, d=None) -> str:
    """Structured data for the pages that carry it: the site itself, and the forecast datasets."""
    graph: list[dict] = []
    if path == "/":
        graph = [{"@type": "WebSite", "name": "HazardPulse", "url": DOMAIN + "/",
                  "description": PAGES["/"].description, "publisher": ORG}, ORG]
    elif path in ("/live/", "/live/earthquake/", "/live/hurricane/", "/live/tornado/", "/evidence/"):
        files = {"/live/": "/data/live-pulse.json", "/live/earthquake/": "/api/v1/live/earthquake",
                 "/live/hurricane/": "/data/live-storms.json", "/live/tornado/": "/data/live-tornadoes.json",
                 "/evidence/": "/data/evidence/replay-index.json"}
        page = PAGES[path]
        ds = {"@type": "Dataset", "name": page.title, "description": page.description, "url": DOMAIN + path,
              "creator": ORG, "isAccessibleForFree": True,
              "license": DOMAIN + "/legal/terms/",
              "distribution": [{"@type": "DataDownload", "encodingFormat": "application/json",
                                "contentUrl": DOMAIN + files[path]}]}
        if d is not None and getattr(d, "built_at", None):
            ds["dateModified"] = d.built_at
        graph = [ds]
    if not graph:
        return ""
    doc = {"@context": "https://schema.org", "@graph": graph}
    return '<script type="application/ld+json">' + json.dumps(doc, separators=(",", ":")) + "</script>"
