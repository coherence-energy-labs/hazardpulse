def document(path: str, main_html: str, *, extra_head: str = "", body_class: str = "", scripts: tuple = ()) -> str:
    """The whole page. ``main_html`` is the page's own content (a ``<main id="main">`` element or its
    inner HTML); ``scripts`` are /assets file names loaded deferred at the end of the body."""
    main = main_html.strip()
    if not main.startswith("<main"):
        main = f'<main id="main" class="page">\n{main}\n</main>'
    tail = "".join(f'\n<script src="{asset(s)}" defer></script>' for s in scripts)
    cls = f' class="{esc(body_class)}"' if body_class else ""
    return (f'<!doctype html>\n<html lang="en">\n{head(path, extra_head)}\n<body{cls}>\n{header(path)}\n{main}\n'
            f"{footer()}{tail}\n</body>\n</html>\n")


MAIN_RE = re.compile(r"<main\b[^>]*>.*</main>", re.S)


def extract_main(page_html: str) -> str:
    m = MAIN_RE.search(page_html)
    if not m:
        raise ValueError("page has no <main> element")
    return m.group(0)


def static_page_file(path: str, dist: Path | None = None) -> Path:
    """The file a site path is served from: ``/`` -> index.html, ``/a/b/`` -> a/b/index.html."""
    base = dist or DIST
    if path == "/404.html":
        return base / "404.html"
    inner = path.strip("/")
    return base / inner / "index.html" if inner else base / "index.html"


EXTRA_HEAD_RE = re.compile(r"<!-- page-head -->.*?<!-- /page-head -->", re.S)
SCRIPTS_RE = re.compile(r'<script src="/assets/([^"?]+)(?:\?v=[0-9a-f]+)?" defer></script>')


def rewrapped(path: str, dist: Path | None = None) -> str:
    """A hand-kept page in the current shell: its own <main>, its page-specific head block (between
    ``<!-- page-head -->`` markers) and its deferred scripts, inside today's head, header and footer."""
    old = static_page_file(path, dist).read_text(encoding="utf-8")
    body_class = (re.search(r'<body class="([^"]*)"', old) or [None, ""])[1]
    extra = EXTRA_HEAD_RE.search(old)
    tail = old[old.rfind("</footer>"):] if "</footer>" in old else ""
    head_extra = (extra.group(0) if extra else "") + jsonld_for(path, None)
    return document(path, extract_main(old), extra_head=head_extra, body_class=body_class,
                    scripts=tuple(SCRIPTS_RE.findall(tail)))


def rewrap(path: str, dist: Path | None = None) -> bool:
    """Re-wrap one hand-kept page; True when it changed."""
    f = static_page_file(path, dist)
    old = f.read_text(encoding="utf-8")
    new = rewrapped(path, dist)
    if new != old:
        f.write_text(new, encoding="utf-8", newline="\n")
        return True
    return False


def rewrap_static_pages(dist: Path | None = None) -> list[str]:
    return [p.path for p in PAGES.values()
            if p.static and static_page_file(p.path, dist).exists() and rewrap(p.path, dist)]


